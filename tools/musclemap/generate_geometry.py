#!/usr/bin/env python3
"""Writes MuscleMapGeometry.kt from regions.py (polygons in the user's chart pixel space, 422x316).

Run from repo root:  python3 tools/musclemap/generate_geometry.py
Coordinates are normalised to 0..1 so the same data drives drawing and hit-testing.
Draw and tap both use ArtworkFit, which handles letterboxing.
"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from regions import FRONT_PX, BACK_PX, W, H

OUT = os.path.join(os.path.dirname(__file__), "..", "..",
                   "app/src/main/java/com/pranav/focus/workout/musclemap/MuscleMapGeometry.kt")

def flat(poly):
    vals = []
    for x, y in poly:
        vals.append(f"{x / W:.4f}f"); vals.append(f"{y / H:.4f}f")
    return "floatArrayOf(" + ", ".join(vals) + ")"

def block(name, data):
    lines = [f"internal val {name}: List<MaskPolygon> = listOf("]
    for key, polys in data.items():
        for p in polys:
            lines.append(f"    MaskPolygon(MuscleGroup.{key}, {flat(p)}),")
    lines.append(")")
    return "\n".join(lines)

src = f"""// GENERATED by tools/musclemap/generate_geometry.py from regions.py. Do not edit by hand.
// Source artwork: user-supplied anatomy chart, muscle_map_chart.png ({W}x{H}).
// Hand-authored approximate boundaries; verified visually against the chart only, not medically validated.
package com.pranav.focus.workout.musclemap

internal const val CHART_WIDTH = {W}f
internal const val CHART_HEIGHT = {H}f

{block("FRONT_POLYGONS", FRONT_PX)}

{block("BACK_POLYGONS", BACK_PX)}
"""
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write(src)
print("wrote", os.path.normpath(OUT))
